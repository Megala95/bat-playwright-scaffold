import fs from "fs";
import path from "path";
import { reviewSource, RULES } from "./reviewSource";
import { Finding, ReviewReport, Severity } from "./types";

/**
 * Runs the script reviewer (src/reviewer/reviewSource.ts) over a set of
 * Playwright test / page-object files and writes script-review-report.json.
 *
 * Usage:
 *   npm run review-scripts                       # tests/, src/pages/ and output/automation/ (when present; minus tests/meta)
 *   npm run review-scripts -- tests/auth src/pages/LoginPage.ts
 *   npm run review-scripts -- --strict           # exit 1 if any ERROR-level finding (CI gate)
 *   npm run review-scripts -- --min warning      # hide info-level findings
 *   npm run review-scripts -- --rules            # print the rule list
 *   npm run review-scripts -- --rules-md         # the same as markdown (source of .github/skills/script-review/references/rules.md)
 */
const ROOT = path.join(__dirname, "..", "..");
const DEFAULT_TARGETS = ["tests", "src/pages", "output/automation"]; // missing folders are simply skipped
const SKIP_DIRS = new Set(["node_modules", "meta", "dist", "test-results", "playwright-report", "blob-report"]);
const RANK: Record<Severity, number> = { error: 3, warning: 2, info: 1 };

export function collectFiles(target: string): string[] {
  const abs = path.isAbsolute(target) ? target : path.join(ROOT, target);
  if (!fs.existsSync(abs)) return [];
  const stat = fs.statSync(abs);
  if (stat.isFile()) return /\.(ts|tsx)$/.test(abs) ? [abs] : [];
  const out: string[] = [];
  for (const name of fs.readdirSync(abs)) {
    if (SKIP_DIRS.has(name)) continue;
    out.push(...collectFiles(path.join(abs, name)));
  }
  return out;
}

export function buildReport(files: string[], minSeverity: Severity = "info"): ReviewReport {
  const findings: Finding[] = [];
  for (const f of files) {
    const rel = path.relative(ROOT, f).split(path.sep).join("/");
    findings.push(...reviewSource(rel, fs.readFileSync(f, "utf-8")));
  }
  const shown = findings.filter((x) => RANK[x.severity] >= RANK[minSeverity]);
  const counts = { error: 0, warning: 0, info: 0 };
  const byCategory: Record<string, number> = {};
  for (const f of shown) {
    counts[f.severity]++;
    byCategory[f.category] = (byCategory[f.category] ?? 0) + 1;
  }
  return { generatedAt: new Date().toISOString(), files: files.length, counts, byCategory, findings: shown };
}

export function formatReport(report: ReviewReport): string {
  const lines: string[] = [];
  let current = "";
  for (const f of report.findings) {
    if (f.file !== current) {
      current = f.file;
      lines.push(`\n${f.file}`);
    }
    lines.push(`  ${f.line}:${f.column}  ${f.severity.padEnd(7)} ${f.ruleId}  ${f.message}`);
    lines.push(`           -> ${f.suggestion}`);
  }
  lines.push(
    `\n[review] ${report.files} file(s): ${report.counts.error} error(s), ${report.counts.warning} warning(s), ${report.counts.info} info.`
  );
  return lines.join("\n");
}

/** Markdown rule table, generated so the skill's reference can never drift from the code. */
export function rulesMarkdown(): string {
  const rows = RULES.map((r) => `| \`${r.id}\` | ${r.severity} | ${r.category} | ${r.title} | ${r.why} |`);
  return [
    "# Reviewer rules",
    "",
    "Generated by `npm run review-scripts -- --rules-md` from `src/reviewer/reviewSource.ts` - do not edit by hand;",
    "`tests/meta/reviewer.spec.ts` fails if this file drifts from the code.",
    "",
    "Suppress one finding with `// review-ignore RULE-ID: <reason why this case is different>` on the same or previous line (a missing reason is ignored).",
    "",
    "| Rule | Severity | Category | What it flags | Why it matters |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

function main(): void {
  const args = process.argv.slice(2);
  if (args.includes("--rules-md")) {
    console.log(rulesMarkdown());
    return;
  }
  if (args.includes("--rules")) {
    for (const r of RULES) console.log(`${r.id.padEnd(9)} ${r.severity.padEnd(8)} ${r.category.padEnd(16)} ${r.title}`);
    return;
  }
  const minIdx = args.indexOf("--min");
  const min = (minIdx !== -1 ? args[minIdx + 1] : "info") as Severity;
  if (!(min in RANK)) {
    // A typo here used to hide every finding and let --strict pass; refuse instead.
    console.error(`[review] --min must be one of: ${Object.keys(RANK).join(", ")} (got "${args[minIdx + 1]}").`);
    process.exit(2);
  }
  const outIdx = args.indexOf("--out");
  const out = outIdx !== -1 ? args[outIdx + 1] : path.join(ROOT, "script-review-report.json");
  const strict = args.includes("--strict");
  const targets = args.filter((a, i) => !a.startsWith("--") && args[i - 1] !== "--min" && args[i - 1] !== "--out");

  const files = (targets.length ? targets : DEFAULT_TARGETS).flatMap(collectFiles);
  if (files.length === 0) {
    console.error("[review] No .ts files found for the given paths.");
    process.exit(1);
  }
  const report = buildReport(files, min);
  fs.writeFileSync(out, JSON.stringify(report, null, 2));
  console.log(formatReport(report));
  console.log(`[review] Wrote ${out}`);
  if (strict && report.counts.error > 0) process.exit(1);
}

if (require.main === module) {
  main();
}
